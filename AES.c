// --- CORE FUNCTIONS ---
void subBytes(byte *s) { for (int i = 0; i < 16; i++) s[i] = sbox[s[i]]; }
void invSubBytes(byte *s) { for (int i = 0; i < 16; i++) s[i] = invSbox[s[i]]; }

void shiftRows(byte *s) {
    byte t[16]; memcpy(t, s, 16);
    s[1] = t[5]; s[5] = t[9]; s[9] = t[13]; s[13] = t[1];
    s[2] = t[10]; s[6] = t[14]; s[10] = t[2]; s[14] = t[6];
    s[3] = t[15]; s[7] = t[3]; s[11] = t[7]; s[15] = t[11];
}

void invShiftRows(byte *s) {
    byte t[16]; memcpy(t, s, 16);
    s[1] = t[13]; s[5] = t[1]; s[9] = t[5]; s[13] = t[9];
    s[2] = t[10]; s[6] = t[14]; s[10] = t[2]; s[14] = t[6];
    s[3] = t[7]; s[7] = t[11]; s[11] = t[15]; s[15] = t[3];
}

byte xtime(byte a) { return ((a << 1) ^ (a & 0x80 ? 0x1b : 0)) & 0xFF; }

byte mul(byte a, byte b) {
    byte p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        byte hi = a & 0x80;
        a = (a << 1) & 0xFF;
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

void mixColumns(byte *s) {
    for (int i = 0; i < 16; i += 4) {
        byte a[4]; memcpy(a, s + i, 4);
        s[i] = xtime(a[0]) ^ xtime(a[1]) ^ a[1] ^ a[2] ^ a[3];
        s[i + 1] = a[0] ^ xtime(a[1]) ^ xtime(a[2]) ^ a[2] ^ a[3];
        s[i + 2] = a[0] ^ a[1] ^ xtime(a[2]) ^ xtime(a[3]) ^ a[3];
        s[i + 3] = xtime(a[0]) ^ a[0] ^ a[1] ^ a[2] ^ xtime(a[3]);
    }
}

void invMixColumns(byte *s) {
    for (int i = 0; i < 16; i += 4) {
        byte a[4]; memcpy(a, s + i, 4);
        s[i] = mul(a[0], 0x0e) ^ mul(a[1], 0x0b) ^ mul(a[2], 0x0d) ^ mul(a[3], 0x09);
        s[i + 1] = mul(a[0], 0x09) ^ mul(a[1], 0x0e) ^ mul(a[2], 0x0b) ^ mul(a[3], 0x0d);
        s[i + 2] = mul(a[0], 0x0d) ^ mul(a[1], 0x09) ^ mul(a[2], 0x0e) ^ mul(a[3], 0x0b);
        s[i + 3] = mul(a[0], 0x0b) ^ mul(a[1], 0x0d) ^ mul(a[2], 0x09) ^ mul(a[3], 0x0e);
    }
}

void addRoundKey(byte *s, byte *k) { for (int i = 0; i < 16; i++) s[i] ^= k[i]; }

void keyExpansion(byte *key, byte *w) {
    memcpy(w, key, 16);
    for (int i = 16; i < 176; i += 4) {
        byte t[4]; memcpy(t, w + i - 4, 4);
        if (i % 16 == 0) {
            byte temp = t[0]; t[0] = sbox[t[1]]; t[1] = sbox[t[2]]; t[2] = sbox[t[3]]; t[3] = sbox[temp];
            t[0] ^= rcon[(i / 16) - 1];
        }
        for (int j = 0; j < 4; j++) w[i + j] = w[i + j - 16] ^ t[j];
    }
}

// --- BLOCK CIPHER OPS ---
void encryptBlock(byte *state, byte *w) {
    addRoundKey(state, w);
    for (int r = 1; r <= 9; r++) {
        subBytes(state); shiftRows(state); mixColumns(state);
        addRoundKey(state, w + r * 16);
    }
    subBytes(state); shiftRows(state); addRoundKey(state, w + 160);
}

void decryptBlock(byte *state, byte *w) {
    addRoundKey(state, w + 160);
    for (int r = 9; r >= 1; r--) {
        invShiftRows(state); invSubBytes(state);
        addRoundKey(state, w + r * 16); invMixColumns(state);
    }
    invShiftRows(state); invSubBytes(state); addRoundKey(state, w);
}

